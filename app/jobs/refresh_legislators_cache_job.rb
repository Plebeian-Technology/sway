# frozen_string_literal: true

# @lat: [[scheduled-job-monitoring#Why RefreshLegislatorsCacheJob rescues each locale independently]]
class RefreshLegislatorsCacheJob < ApplicationJob
  queue_as :background

  include Sentry::Cron::MonitorCheckIns

  # @lat: [[scheduled-job-monitoring#Why a total-failure run reports rather than fails]]
  ALL_LOCALES_FAILED_ALARM = "Every locale the legislators refresh attempted failed, so no roster was refreshed and no pull request was opened. The individual errors are on their own events, one per locale."

  # @lat: [[scheduled-job-monitoring#Why the slug is written out rather than derived]]
  MONITOR_SLUG = "refresh-legislators-cache"
  # @lat: [[scheduled-job-monitoring#The crontab constant has to match the schedule file by hand]]
  MONITOR_CRONTAB = "0 3 * * 0"
  # @lat: [[scheduled-job-monitoring#Why a weekly job gets an hour of margin]]
  MONITOR_CHECKIN_MARGIN_MINUTES = 60

  MONITOR_CONFIG = Sentry::Cron::MonitorConfig.from_crontab(
    MONITOR_CRONTAB,
    checkin_margin: MONITOR_CHECKIN_MARGIN_MINUTES
  )

  # @lat: [[scheduled-job-monitoring#Why a cron monitor and not another error report]]
  sentry_monitor_check_ins(
    slug: MONITOR_SLUG,
    monitor_config: MONITOR_CONFIG
  )

  def perform(force: false)
    changed_files = {}
    attempted_count = 0
    failed_count = 0

    SwayLocale.find_each do |locale|
      klass = refresher_for(locale)
      next if klass.nil?

      attempted_count += 1
      result = klass.new(locale, force: force).call
      changed_files.merge!(result.changed_files) if result.changed_files.any?
    rescue => e
      failed_count += 1
      SwayLogging.log_exception("refresh_legislators_cache.locale_failed", exception: e, locale: locale.name)
      Sentry.capture_exception(e, extra: {locale: locale.name})
    end

    if attempted_count.positive? && failed_count == attempted_count
      Sentry.capture_message(
        ALL_LOCALES_FAILED_ALARM,
        level: :error,
        extra: {attempted_locales: attempted_count}
      )
    end

    if changed_files.any?
      branch = "seeds/refresh-legislators-#{Date.current.strftime("%Y%m%d")}"
      GitHubPrService.new.open_pr(
        branch: branch,
        title: "chore(seeds): refresh legislators cache #{Date.current}",
        body: "Auto-generated by RefreshLegislatorsCacheJob. " \
                "Changed: #{changed_files.keys.join(", ")}",
        files: changed_files
      )
      SwayLogging.info("[RefreshLegislatorsCacheJob] Opened PR on branch #{branch}")
    else
      SwayLogging.info("[RefreshLegislatorsCacheJob] No locale changes — skipping PR")
    end
  end

  private

  # @lat: [[current-legislator-term#A locale with no declared calendar is skipped, not refused]]
  def refresher_for(locale)
    rules = locale.declared_jurisdiction_rules
    if rules.nil?
      SwayLogging.warn(
        "refresh_legislators_cache.undeclared_locale",
        sway_locale: locale.name,
        note: "no roster refresher declared, so nothing was fetched for it"
      )
      return nil
    end

    roster_rules = begin
      rules.roster_rules if rules.respond_to?(:roster_rules)
    rescue => _e
      nil
    end

    retrieval = rules&.roster_retrieval
    retrieval ||= (roster_rules&.dig(:retrieval) || roster_rules&.dig("retrieval") ||
                   roster_rules&.dig(:retrieval_strategy) || roster_rules&.dig("retrieval_strategy") ||
                   roster_rules&.dig(:engine) || roster_rules&.dig("engine"))&.to_s

    if retrieval == "unavailable" || retrieval == "curated" || retrieval.blank?
      SwayLogging.info(
        "refresh_legislators_cache.unavailable_refresher",
        sway_locale: locale.name,
        note: "automatic roster refresh is unavailable for manual locale"
      )
      return nil
    end

    LegislatorsCache::BaseRefresh
  end
end
